"""**買い目を全面横断で並べ替える。**「面の中で安い」は買われる理由にならん。

## なんで要るか
2026-08-17、3面のSOLD率を経過時間を揃えて測ったら順位が付いた:

| 面 | SOLD率 | 経過 |
|---|---|---|
| Yahoo!フリマ | **73%** | 27時間 |
| メルカリ | 10% | 57時間 |
| ラクマ | **0%** | 27時間 |

交絡は無い(純利・割引の深さ・領域構成が同じ)。原因は**同じ型番でラクマの方が高い**:

    HN-65N4   ラクマ¥39,800 vs フリマ¥22,000   1.81倍
    WH36DD    ラクマ¥22,550 vs フリマ¥15,000   1.50倍

**買い線を割っとっても、他の面にもっと安い玉が並んどったら買われん。**
転売業者は全面を見とる。せやから盤も全面を横断して並べな、実態とズレる。

### ただし「ラクマが高いから売れん」は**間違いやった**(2026-08-17に訂正)
5型番で測って「中央1.04倍でラクマが高い」と書いたが、7型番で見直したら
**ラクマが最安の型番が3つある**:

    td173drgx  ラクマ¥20,350 < フリマ¥25,300
    hn65n4     ラクマ¥39,800 < メルカリ¥40,000
    c3605da    ラクマ¥12,000 < メルカリ¥13,800

**安いのに27時間で0件しか売れとらん。値段では説明できん。**
残る仮説は「ラクマは買い手の数が少ない」やが、まだ確かめとらん。

## 出す形
同じ型番の玉を**全面まとめて安い順**に並べ、各型番の最安に印を付ける。
「その型番でいま一番安いのはどこか」が1行で分かる。
"""
from __future__ import annotations

import pandas as pd

# 面の順位(2026-08-17の実測)。同値のとき、速く売れる面を上に出す
MARKET_RANK = {"Yahoo!フリマ": 0, "メルカリ": 1, "ラクマ": 2}
MARKET_NOTE = {
    "Yahoo!フリマ": "73%が27hで消える。**速度が全て**",
    "メルカリ": "10%/57h。玉は残るが競争も薄い",
    "ラクマ": "0%/27h。フリマより高いことが多い",
}


def rank(df: pd.DataFrame) -> pd.DataFrame:
    """型番ごとに全面をまとめ、最安に印を付ける。

    返す列を足す:
      同型番の最安  その型番・**同じ状態**で全面いちばん安い値
      最安か        ○ ならこの玉が全面最安
      他面との差    最安との差額(0なら自分が最安)
    """
    if df.empty or "family" not in df or "price" not in df:
        return df
    d = df.copy()
    d["price"] = pd.to_numeric(d["price"], errors="coerce")
    # 🚨 **新品と中古を同じ棚に並べたらあかん**(2026-08-25)。
    # 「同型番の最安」は買い手が実際に見比べる集合や。中古¥22,000 と
    # 新品¥39,800 を並べて「中古が最安」と言うても、新品を探しとる買い手は
    # 動かん。出口の中央値を状態で割ったのと同じ軸をここにも当てる。
    # 状態が空の行(混ぜとった頃の古い走査)は、それ自体が1つの群になる
    key = ["family", "状態"] if "状態" in d else ["family"]
    if "状態" in d:
        # 🚨 **groupby は NaN の群を黙って落とす。** 状態がまだ付いとらん行
        # (走査し直しとらん面)が最安の計算から丸ごと消えて、「同型番の最安」が
        # NaN になる。空文字に潰して**1つの群として扱う**——欠損を消すんやのうて
        # 「状態が分からん群」として残す(2026-08-25)
        d["状態"] = d["状態"].fillna("").astype(str)
    lo = d.groupby(key)["price"].transform("min")
    d["同型番の最安"] = lo
    # **同じ値段の玉が複数あったら全部「最安」になってまう。**
    # 型番ごとに1つだけ残す(同値なら速く売れる面を優先)
    d["_mk0"] = d.get("市場", "").map(lambda m: MARKET_RANK.get(m, 9))
    d = d.sort_values(key + ["price", "_mk0"])
    first = ~d.duplicated(key, keep="first")
    d["最安か"] = first.map({True: "○", False: ""})
    d["他面との差"] = (d["price"] - lo).astype("Int64")
    # 面の数を数える。**2面以上に出とる型番は、そもそも競争が厚い**
    d["出とる面数"] = d.groupby(key)["市場"].transform("nunique") \
        if "市場" in d else 1
    d["_mk"] = d.get("市場", "").map(lambda m: MARKET_RANK.get(m, 9))
    return d.sort_values(["最安か", "net", "_mk"],
                         ascending=[False, False, True])


def only_cheapest(df: pd.DataFrame) -> pd.DataFrame:
    """全面最安の玉だけ。**実際に買われるのはこれ**やという仮説の表示。"""
    if df.empty or "最安か" not in df:
        return df
    return df[df["最安か"] == "○"]
