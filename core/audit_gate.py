# -*- coding: utf-8 -*-
"""**想定純利の逆選別** — 推定利益で並べたリストは、上に行くほど誤りが濃い。

## 何を名前づけたか
2026-08-11までに、監査のたびに死んだのは**毎回リストの上位**やった:

| 化けた玉 | 見かけの純利 | 正体 |
|---|---|---|
| ES-335 / GIBSON CUSTOM | — | 辞書がブランド最初の1語で畳まれとった |
| 「Inspired by」 | ¥530,000 | 模倣品が本家の相場と比べられた |
| `soldano SERIESⅡ SP-77` | ¥136,340 | ギターアンプがセルマーのサックスに当たった |
| `YAS-82Zで使用` ネック | ¥150,024 | サックスのネック単体が本体と比べられた |
| `DSC-RX10M3 … RX10M4` | ¥80,632 | 世代併記でM3の玉をM4の相場と比べた |

理屈は単純や:

    本物の市場の歪み  = 小さい (検品後の実測で1本平均 ¥10,982)
    誤マッチが作る歪み = いくらでもデカい (比較対象が別物やから上限が無い)

せやから**想定純利で降順に並べた瞬間、そのリストは誤り濃度の降順**になる。
上位ほど「本物の大勝ち」やのうて「比較対象がズレた玉」の割合が上がる。
これは運の問題やのうて、並べ替えの数学的な帰結や。

## 運用への含意
**上位は買いキューやない。監査キューや。**

月3.8本(2026-08-11実測)しか出んのやから、全数を人手で読んでも手間はゼロに等しい。
せやからこの盤では:

  * **自動買い・自動入札は実装せん。** 人手確認を通っとらん玉は買わん
  * 純利の降順リストは「監査キュー」として出す。ラベルもそう書く
  * 上位 AUDIT_TOP_N 本には、人手確認が済むまで警告を出し続ける

## この規律を外してええ条件
「上位N本を人手で読んで、M回連続で誤マッチがゼロやった」が積み上がったとき。
それまでは外さん。2026-08-11時点の実績は **上位2本中2本が誤マッチ**や。
"""
from __future__ import annotations

import pandas as pd

# 監査必須とみなす上位本数。全数が理想やが、本数が増えたときの下限として置く
AUDIT_TOP_N = 10

# **人手確認なしの自動買いは、この盤では存在せん。**
# 定数として置いとくのは、将来「自動化しようか」と考えたときに
# ここを True に書き換える手が止まるようにするためや。
AUTO_BUY_ENABLED = False

AUDIT_NOTE = (
    "**上位は買いキューやのうて監査キューや。** 想定純利で並べると、"
    "上に行くほど誤マッチの濃度が上がる——本物の歪みは1本平均¥10,982と小さいのに、"
    "比較対象がズレた玉の見かけの利益には上限が無いからや。"
    "2026-08-11の実測では上位2本が2本とも誤マッチ(ギターアンプ→サックス¥136,340、"
    "ネック単体→本体¥150,024)やった。**人手で本文を読むまで買わん。**"
)


def mark(df: pd.DataFrame, net_col: str = "net") -> pd.DataFrame:
    """**買い線からの乖離が大きい順**に並べ、上位に監査フラグを立てる。

    2026-08-19、乖離で並べる根拠が実測で出た。ゼンハイザー HD800 の
    生きた出品を見に行ったら、買い線¥71,429を割っとった2本が**両方ケーブル**やった:

        ¥  9,800  ORB Clearforce … HD800 オーディオケーブル   乖離 87%
        ¥ 27,000  ALO AUDIO SXC 8 HD800 リケーブル            乖離 62%
        ¥101,500  ゼンハイザー HD800 CH800S セット             買い線を超えとる
        ¥105,000  ゼンハイザー HD800                          買い線を超えとる

    **誤マッチは安いから、粗利がデカく見える側に必ず出る。**本物の玉は買い線の
    すぐ下に張り付くが、別物と比べとる玉は際限なく下に出る。せやから
    「乖離がデカい順」は、そのまま「疑わしい順」や。

    純利の降順も同じ向きに効くが、乖離は**値段の桁を跨いでも比べられる**。
    ¥9,800の誤マッチと¥200,000の本物を、純利では並べられん。

    返す列:
      監査キュー順  1始まりの順位(乖離の大きい順)
      買い線乖離    (買い線 - 価格) / 買い線。大きいほど疑わしい
      要人手確認    上位N本か、または人手判定が未記入なら True
    """
    if df.empty or net_col not in df.columns:
        return df
    out = df.copy()
    if {"price", "buy_line"} <= set(out.columns):
        p = pd.to_numeric(out["price"], errors="coerce")
        b = pd.to_numeric(out["buy_line"], errors="coerce")
        out["買い線乖離"] = ((b - p) / b).where(b > 0)
        out = out.sort_values(["買い線乖離", net_col],
                              ascending=[False, False])
    else:
        # 買い線が無い盤では従来どおり純利の降順。向きは同じや
        out = out.sort_values(net_col, ascending=False)
    out = out.reset_index(drop=True)
    out["監査キュー順"] = out.index + 1
    human = out["人手判定"] if "人手判定" in out.columns else pd.Series(
        [""] * len(out), index=out.index)
    out["要人手確認"] = (out["監査キュー順"] <= AUDIT_TOP_N) | (
        human.fillna("").astype(str).str.strip() == "")
    return out


